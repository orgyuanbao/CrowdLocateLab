"""Audit regression fixtures are fabricated test data, never research evidence."""
import copy
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from audit import audit_run, _canonical, _digest, _text_hash


class AuditTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="crowdloc-audit-tests-")
        self.root = Path(self.temporary.name)/"relocated_project"
        self.run = self.root/"runs"/"renamed_fixture"
        self.run.mkdir(parents=True)
        hashes = {}
        for name in ("run_agent.py", "benchmark.py", "localization/model.py", "tools/toolkit.py", "agent_runtime/controller.py"):
            path = self.root/name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("# Isolated fixture, not research implementation\n", encoding="utf-8")
            hashes[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        self.identity = {"config": {"source_hashes": hashes}, "provider": "fixture_not_a_model"}
        self.write(self.run/"protocol.json", {"source_hashes": hashes})
        self.events = []
        self.append("decision", {"decision": "initialize", "identity": self.identity,
                                 "identity_sha256": _digest(self.identity)})
        self.prompt = "Unit-test fixture; no model inference.\nSecond line."
        self.schema = {"type": "object", "description": "Fixture schema"}
        self.request = dict(request_id="planner-0001", prompt=self.prompt, purpose="planner",
                            prompt_sha256=_text_hash(self.prompt), schema_sha256=_digest(self.schema))
        self.append("model_request", self.request)
        directory = self.run/"model_calls"/"planner-0001"
        directory.mkdir(parents=True)
        self.directory = directory
        # Explicit Windows newline bytes must normalize back to the original
        # Python string, just as the real provider's write_text/read_text does.
        (directory/"prompt.txt").write_bytes(self.prompt.replace("\n", "\r\n").encode("utf-8"))
        self.write(directory/"schema.json", self.schema)
        response = {"fixture": "Response generated by a unit test, not an LLM."}
        self.write(directory/"response.json", response)
        raw = {"type": "turn.completed", "usage": {"input_tokens": 3, "output_tokens": 2}}
        (directory/"cli_events.jsonl").write_text(_canonical(raw)+"\n", encoding="utf-8")
        (directory/"stderr.txt").write_text("", encoding="utf-8")
        metadata = dict(request_id="planner-0001", prompt_sha256=self.request["prompt_sha256"],
                        schema_sha256=self.request["schema_sha256"], status="completed", raw_event_count=1,
                        unexpected_tools=[], usage=raw["usage"], model_identifier=None,
                        model_identifier_source="not_reported_by_cli")
        self.write(directory/"metadata.json", metadata)
        old = "Z:/old_machine/old_project/runs/old_name/model_calls/planner-0001/"
        self.response = dict(request_id="planner-0001", response=response,
                             prompt_sha256=metadata["prompt_sha256"], schema_sha256=metadata["schema_sha256"],
                             artifacts={"directory": old, "response": old+"response.json",
                                        "metadata": old+"metadata.json", "raw_events": old+"cli_events.jsonl"},
                             unexpected_tools=[], usage=raw["usage"], model_identifier=None,
                             model_identifier_source="not_reported_by_cli", replay=False)
        self.append("model_response", self.response)
        self.evidence = []
        for number in (1, 2):
            evidence = {"overall": {"mean_m": float(number)}, "rows": [{"case_id": "fixture", "error_m": float(number)}]}
            relative = f"experiments/call_{number:03d}_discovery_fixture.json"
            self.write(self.run/"tools"/relative, evidence)
            entry = dict(overall=evidence["overall"], evidence_path=relative, evidence_sha256=_digest(evidence))
            self.evidence.append(entry)
            self.append("tool_result", {"action": "run_experiment", "result": {"metrics": {"fixture": entry}}})
        self.write(self.run/"tools"/"tool_state.json", {"evaluations": {"discovery:fixture": self.evidence[-1]}, "frozen": False})
        self.flush()

    def tearDown(self):
        self.temporary.cleanup()

    def write(self, path, value):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")

    def append(self, kind, payload):
        event = dict(sequence=len(self.events)+1, previous_sha256=self.events[-1]["event_sha256"] if self.events else "0"*64,
                     type=kind, payload=copy.deepcopy(payload), time_utc="fixture_not_a_timestamp")
        event["event_sha256"] = _digest(event)
        self.events.append(event)

    def flush(self, status="stopped"):
        (self.run/"events.jsonl").write_text("".join(_canonical(event)+"\n" for event in self.events), encoding="utf-8")
        self.state = dict(identity=self.identity, identity_sha256=_digest(self.identity), status=status,
                          frozen=False, is_replay=False, last_event_sequence=len(self.events),
                          last_event_sha256=self.events[-1]["event_sha256"])
        self.write(self.run/"state.json", self.state)

    def test_relocated_paths_and_windows_newlines_verify_without_original_copy(self):
        result = audit_run(self.root, self.run)
        self.assertTrue(result["integrity_ok"], result["findings"])
        self.assertEqual(result["exit_code"], 0)
        self.assertEqual(result["counts"]["completed_model_artifacts"], 1)
        self.assertEqual(result["counts"]["evidence_files"], 2)
        self.assertEqual(result["status"], "passed_unfrozen")

    def test_historical_evidence_is_verified_even_when_not_latest(self):
        path = self.run/"tools"/self.evidence[0]["evidence_path"]
        value = json.loads(path.read_text(encoding="utf-8"))
        value["rows"][0]["error_m"] = 999.
        self.write(path, value)
        result = audit_run(self.root, self.run)
        self.assertEqual(result["exit_code"], 1)
        self.assertIn("historical_evidence_hash", {issue["code"] for issue in result["findings"]})

    def test_state_checkpoint_and_event_content_tampering_fail(self):
        self.state["last_event_sha256"] = "f"*64
        self.write(self.run/"state.json", self.state)
        result = audit_run(self.root, self.run)
        self.assertIn("state_event_hash", {issue["code"] for issue in result["findings"]})
        self.flush()
        self.events[0]["payload"]["altered"] = True
        (self.run/"events.jsonl").write_text("".join(_canonical(e)+"\n" for e in self.events), encoding="utf-8")
        result = audit_run(self.root, self.run)
        self.assertIn("event_content_hash", {issue["code"] for issue in result["findings"]})

    def test_raw_response_and_metadata_mismatches_are_detected(self):
        self.write(self.directory/"response.json", {"fixture": "Altered raw response"})
        result = audit_run(self.root, self.run)
        self.assertIn("response_file_hash", {issue["code"] for issue in result["findings"]})
        self.write(self.directory/"response.json", self.response["response"])
        metadata = json.loads((self.directory/"metadata.json").read_text(encoding="utf-8"))
        metadata["raw_event_count"] = 100
        self.write(self.directory/"metadata.json", metadata)
        result = audit_run(self.root, self.run)
        self.assertIn("raw_event_count", {issue["code"] for issue in result["findings"]})

    def test_live_pending_request_is_not_reported_as_completed_or_corrupt(self):
        self.append("model_request", dict(self.request, request_id="planner-0002"))
        self.flush(status="running")
        result = audit_run(self.root, self.run)
        self.assertEqual(result["status"], "passed_in_progress", result["findings"])
        self.assertEqual(result["counts"]["pending_model_requests"], 1)
        self.assertEqual(result["counts"]["completed_model_artifacts"], 1)
        strict = audit_run(self.root, self.run, require_frozen=True)
        self.assertEqual(strict["exit_code"], 3)

    def test_live_checkpoint_may_lag_at_a_valid_chain_prefix(self):
        self.flush(status="running")
        self.state["last_event_sequence"] = len(self.events)-1
        self.state["last_event_sha256"] = self.events[-2]["event_sha256"]
        self.write(self.run/"state.json", self.state)
        result = audit_run(self.root, self.run)
        self.assertTrue(result["integrity_ok"], result["findings"])
        self.assertIn("state_checkpoint_lag", {issue["code"] for issue in result["findings"]})
        self.state["status"] = "stopped"
        self.write(self.run/"state.json", self.state)
        self.assertFalse(audit_run(self.root, self.run)["integrity_ok"])

    def test_source_change_is_detected(self):
        (self.root/"tools"/"toolkit.py").write_text("# Altered implementation\n", encoding="utf-8")
        result = audit_run(self.root, self.run)
        self.assertEqual(result["exit_code"], 1)
        self.assertIn("source_hash", {issue["code"] for issue in result["findings"]})


if __name__ == "__main__":
    unittest.main()
